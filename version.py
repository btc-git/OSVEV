"""OSVEV version and source-revision identification."""

from functools import lru_cache
from pathlib import Path
import subprocess
import sys

__version__ = "2.0.0"
APP_NAME = "OSVEV"
COPYRIGHT = "Copyright \u00a9 2026 CrimLawTech LLC"
LICENSE_NAME = "GNU General Public License v3.0 or later (GPL-3.0-or-later)"
SOURCE_URL = "https://github.com/btc-git/OSVEV"


def resource_path(name: str) -> Path:
    """Path to a file shipped beside the sources or inside the PyInstaller bundle."""
    return Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent)) / name


@lru_cache(maxsize=1)
def git_commit() -> str:
    """Commit recorded at build time, else the working tree's commit (``+dirty`` if modified)."""
    try:
        from _build_info import GIT_COMMIT  # generated by osvev.spec; not tracked
        return GIT_COMMIT
    except ImportError:
        pass
    root = Path(__file__).resolve().parent
    flags = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--short=12", "HEAD"], cwd=root, capture_output=True,
            text=True, check=True, creationflags=flags, timeout=5,
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=no"], cwd=root,
            capture_output=True, text=True, check=True, creationflags=flags, timeout=5,
        ).stdout.strip()
        return commit + ("+dirty" if dirty else "")
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def version_string() -> str:
    return f"{APP_NAME} {__version__} (commit {git_commit()})"
